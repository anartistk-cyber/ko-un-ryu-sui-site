// answers: 12問分の選択（0〜3）。軸ごと（3問ずつ）に 3-value 点を足し、いちばん高い軸（同点は組み合わせ）から結果の文言を決める。
// 元アプリにあった「％」の表示は、点数を加工して見せるものだったため、採用サイトでは出さない。
export function describeResult(answers: number[], track: TrackId): MatchResult {
  const scores = [0, 0, 0];
  answers.slice(0, 9).forEach((value, i) => { scores[Math.floor(i / 3)] += 3 - value; });
  const seed = answers.reduce((hash, value) => Math.imul(hash ^ (value + 1), 16777619) >>> 0, track === "career" ? 2166136261 : 2246822519);
  const highest = Math.max(...scores);
  const leading = scores.map((s, i) => (s === highest ? i : -1)).filter(i => i >= 0);
  let story: [string, string];
  if (highest < 5) story = ["「好き」を見つけるところから", "今回の回答をヒントに、接客・技術・チームで働くことの中から、もっと知りたいと思うものを探してみましょう。実際の仕事を見ると、自分が心地よく働ける場面が見つかるかもしれません。"];
  else if (leading.length === 3) story = ["人も、技術も、大切に", "仲間と協力すること、お客様の気持ちを聞くこと、教わったことを試すこと。どれにも目を向けられるのが、あなたらしさです。"];
  else story = leading.length === 1 ? STRENGTHS[leading[0]] : COMBINATIONS[leading.join("")];
  const interest = CHOICE[track][2][answers[11] + 1];
  return { title: story[0], description: story[1], interest, tip: TIPS[(seed >>> 8) % TIPS.length] };
}

