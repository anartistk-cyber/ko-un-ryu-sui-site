export const QUESTION_COUNT = 12;
export type Option = { value: number; text: string };
export type Question = { prompt: string; options: Option[] };

// index: 0〜11。1〜9問目は、選択肢が毎回同じ並び（いちばん上が一番よい答え）にならないよう、問ごとに並びをずらして出す。
export function questionAt(track: TrackId, index: number): Question {
  if (index < 9) {
    const [prompt, ...choices] = SCENARIOS[track][index];
    return { prompt, options: choices.map((_, position) => { const value = (position + index + 1) % choices.length; return { value, text: choices[value] }; }) };
  }
  const [prompt, ...choices] = CHOICE[track][index - 9];
  return { prompt, options: choices.map((text, value) => ({ value, text })) };
}

